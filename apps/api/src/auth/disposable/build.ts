import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// Compile the vendored disposable-domain list into a TS module (docs/plans/step-11.md 2.4, D10).
//
//   pnpm --filter @tinyglow/api disposable:build
//
// Reads `disposable_email_blocklist.conf` (vendored verbatim from
// github.com/disposable-email-domains/disposable-email-domains, CC0-1.0, see README.md), drops
// blank lines and `#` comments, lowercases, trims, strips leading/trailing dots, de-duplicates and
// sorts, then writes `blocklist.generated.ts`. The output is deterministic (same input, same
// bytes) and already in Biome's format, so CI can diff it against a fresh build
// (.github/scripts/abuse-hygiene.sh). Nothing reads the `.conf` at runtime: tsup bundles the
// generated module like any other source file.

const here = (name: string) => fileURLToPath(new URL(name, import.meta.url));
const SOURCE = here("./disposable_email_blocklist.conf");
const TARGET = here("./blocklist.generated.ts");

/** A DNS name of at least two labels (letters, digits, hyphens), as the upstream list holds. */
const DOMAIN_RE = /^(?=.{3,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z0-9-]{2,63}$/;

export function parseBlocklist(text: string): string[] {
  const out = new Set<string>();
  const bad: number[] = [];
  text.split(/\r?\n/).forEach((raw, i) => {
    const line = raw.trim().toLowerCase();
    if (line === "" || line.startsWith("#")) return;
    const domain = line.replace(/^\.+|\.+$/g, "");
    if (!DOMAIN_RE.test(domain)) {
      bad.push(i + 1);
      return;
    }
    out.add(domain);
  });
  if (bad.length > 0) {
    throw new Error(`disposable list: ${bad.length} malformed line(s), first at line ${bad[0]}`);
  }
  // Code-unit order (not locale order) keeps the output identical on every machine.
  return [...out].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

export function renderModule(domains: readonly string[]): string {
  const lines = [
    "// Generated by `pnpm --filter @tinyglow/api disposable:build` from disposable_email_blocklist.conf",
    "// (vendored, CC0-1.0; see README.md in this directory). Do not edit by hand; CI fails when this",
    "// file is out of date.",
    "",
    `/** ${domains.length} disposable email domains, lowercase, sorted, de-duplicated. */`,
    "export const DISPOSABLE_DOMAINS: readonly string[] = [",
    ...domains.map((d) => `  "${d}",`),
    "];",
    "",
  ];
  return lines.join("\n");
}

function main(): void {
  const domains = parseBlocklist(readFileSync(SOURCE, "utf8"));
  if (domains.length === 0) throw new Error("disposable list: no domains");
  writeFileSync(TARGET, renderModule(domains));
  console.log(`disposable:build wrote ${domains.length} domains`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main();
}
